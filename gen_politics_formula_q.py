"""政治材料题补充：为 22 条公式里「暂无配套题」的卡补上可练的真题型。
   每题 5—6 个采分点（其中至少 4 个 is_key）+ 1—2 个典型错误点，
   与既有 PO001—PO064 同构，字段完全一致。"""
import hashlib

SRC = "内置 · 教研编写（道德与法治 / 思想政治）"

ITEMS = []


def q(id, stage, grade, scope, genre, formula, stem, passage, points,
      score=4, diff=3, tags=(), why=""):
    key = [p for p in points if p.get("is_key")]
    assert len(key) >= 3, (id, "采分点不足")
    for p in points:
        p.setdefault("w", 1 if p.get("is_key") else 0)
        p.setdefault("trap_type", None)
        p.setdefault("hint", "")
    fp = hashlib.md5((id + stem).encode("utf-8")).hexdigest()[:12]
    ITEMS.append({
        "id": id, "source": SRC, "subject": "politics", "stage": stage,
        "grade": grade, "genre": genre, "content_scope": scope,
        "memory_type": "concept", "mode": "points", "stem": stem,
        "passage": passage, "options": [], "points": points,
        "formula_ref": formula, "total_score": score,
        "reference_answer": "；".join(p["text"] for p in key),
        "time_anchor": None,
        "tags": ["内置", "非选择题"] + list(tags) + ["采分点自评"],
        "difficulty": diff, "difficultyWhy": why,
        "question_fingerprint": fp,
    })


def k(text, cause="要点不全", hint=""):
    return {"text": text, "is_key": True, "cause": cause, "hint": hint}


def w(text, cause, hint=""):
    return {"text": text, "is_key": False, "cause": cause, "hint": hint}


