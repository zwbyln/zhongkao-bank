import hashlib


def fp(q):
    keys = [q.get("stem", "")]
    for o in (q.get("options") or []):
        if o.get("is_correct"):
            keys.append(o.get("text", ""))
    for p in (q.get("points") or []):
        if p.get("is_key"):
            keys.append(p.get("text", ""))
    return hashlib.sha256("|".join(keys).encode("utf-8")).hexdigest()[:12]


def opt(k, text, correct=False, trap=None, ana=""):
    return {"key": k, "text": text, "is_correct": correct,
            "trap_type": trap, "option_analysis": ana}


def pt(text, key=True, w=1, cause="", trap=None, hint=""):
    return {"text": text, "is_key": key, "w": w if key else 0,
            "cause": cause, "trap_type": trap, "hint": hint}


def mk(**kw):
    q = {
        "id": kw["id"],
        "source": "内置 · 教研编写（道德与法治 / 思想政治）",
        "subject": "politics",
        "stage": kw.get("stage", "初中"),
        "grade": kw.get("grade", "九"),
        "genre": kw.get("genre", "政治单选"),
        "content_scope": kw["scope"],
        "memory_type": kw.get("mt", "concept"),
        "mode": kw.get("mode", "single"),
        "stem": kw["stem"],
        "passage": kw.get("passage", ""),
        "options": kw.get("options", []),
        "points": kw.get("points", []),
        "formula_ref": kw.get("formula", "主体判断 → 对应考点 → 排除绝对化与主体错位项"),
        "total_score": kw.get("score", 2 if kw.get("mode", "single") == "single" else 4),
        "reference_answer": kw.get("answer", ""),
        "time_anchor": None,
        "tags": kw.get("tags", ["内置", "选择题", "道德与法治"]),
        "difficulty": kw.get("diff", 2),
        "difficultyWhy": kw.get("why", ""),
    }
    if q["mode"] == "points":
        q["reference_answer"] = "；".join([p["text"] for p in q["points"] if p["is_key"]])
    q["question_fingerprint"] = fp(q)
    return q


ITEMS = []


def S(**kw):
    ITEMS.append(mk(**kw))


def P(**kw):
    kw["mode"] = "points"
    kw.setdefault("genre", "政治材料")
    kw.setdefault("tags", ["内置", "非选择题", "道德与法治", "采分点自评"])
    ITEMS.append(mk(**kw))


