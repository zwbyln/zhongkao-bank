def fp(q):
    """题目指纹：题干 + 正确答案的哈希，用于去重。"""
    keys = [q.get("stem", "")]
    for o in (q.get("options") or []):
        if o.get("is_correct"):
            keys.append(o.get("text", ""))
    for p in (q.get("points") or []):
        if p.get("is_key"):
            keys.append(p.get("text", ""))
    raw = "|".join(keys).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()[:12]


def opt(k, text, correct=False, trap=None, ana=""):
    return {"key": k, "text": text, "is_correct": correct,
            "trap_type": trap, "option_analysis": ana}


def pt(text, key=True, w=1, cause="", trap=None, hint=""):
    return {"text": text, "is_key": key, "w": w if key else 0,
            "cause": cause, "trap_type": trap, "hint": hint}


