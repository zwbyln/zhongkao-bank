"""政治（道德与法治 / 思想政治）题库生成器。

为什么这么编（教研口径）：

1. **范围对齐课标**：初中按《道德与法治》课标九大主题（成长中的我、我与他人、
   我与国家社会、法律、国情、责任…），高中按必修 1—4（中国特色社会主义、
   经济与社会、政治与法治、哲学与文化）。中考/高考的真实考法不是背条文，
   而是「给一段材料，判断主体、找出对应考点、写出做法」。

2. **题型的落点**：道德与法治中考主流是三段式——
   单选（价值判断）、材料分析（是什么—为什么—怎么做）、
   情境探究（给情境判断做法对不对 + 说明理由）。
   所以这里只出这三种，不出偏题怪题。

3. **每道非选择题都带采分点**：政治主观题给分是「采点给分」，
   答对方向但漏点就丢分。采分点里刻意放几类常见错答作干扰
   （主体错位、只喊口号不落实、答非所问），这样孩子做错的
   不是「不知道」，而是「答不全 / 答偏」，正好被错因本接住。

4. **条款不编造**：涉及法律条文的，只写「宪法规定」「民法典规定」
   这种可确证的表述，不臆造条号。时政内容另行由时政模块管理，
   不混进题库——时政过期快，题库要稳。
"""

