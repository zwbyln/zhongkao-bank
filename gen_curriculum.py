def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="bank/curriculum-2026.json")
    a = ap.parse_args()
    items = H + C
    # 计算指纹（与 merge_bank 同口径：题干 + 正确答案）
    seen = set()
    for x in items:
        raw = re.sub(r"[\s\u3000·、，。；：！？,.;:!?\"'“”‘’()（）\[\]【】]+", "",
                     str(x["stem"]) + "|" + str(x.get("reference_answer") or ""))
        import hashlib
        x["question_fingerprint"] = hashlib.md5(raw.encode("utf-8")).hexdigest()
        if x["question_fingerprint"] in seen:
            raise SystemExit("重复题：" + x["id"])
        seen.add(x["question_fingerprint"])
    doc = {
        "format": "zx-bank-group-v1",
        "name": "内置 · 中考卷面补齐（非选择题）",
        "subject": "mixed",
        "items": items,
    }
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    json.dump(doc, open(a.out, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    from collections import Counter
    print("生成", len(items), "道 →", a.out)
    print(Counter((x["subject"], x["genre"]) for x in items))


if __name__ == "__main__":
    main()
